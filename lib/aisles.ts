export function isAisle(v: unknown): v is Aisle {
  return typeof v === 'string' && AISLES.some((a) => a.id === v)
}

export function guessAisle(itemName: string): Aisle {
  const haystack = itemName.toLowerCase().trim()
  if (!haystack) return 'אחר'
  for (const aisle of AISLES) {
    if (aisle.keywords.some((k) => haystack.includes(k.toLowerCase()))) return aisle.id
  }
  return 'אחר'
}

export function aisleOrder(a: string | null): number {
  if (!a) return 999
  const def = AISLES.find((x) => x.id === a)
  return def?.order ?? 999
}

export function aisleIcon(a: string | null): string {
  if (!a) return '🛒'
  return AISLES.find((x) => x.id === a)?.icon ?? '🛒'
}
